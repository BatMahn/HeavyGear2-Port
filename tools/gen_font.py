# Generates src/render/hudfont.h: ASCII 32..126 glyph atlas (alpha) from DejaVu Sans Mono Bold
# (Bitstream Vera / DejaVu licence: free to embed and redistribute).
from PIL import Image, ImageDraw, ImageFont
import sys
font = ImageFont.truetype(sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf', 15)
CW, CH, COLS = 10, 18, 16
img = Image.new('L', (CW * COLS, CH * 6), 0)
d = ImageDraw.Draw(img)
for c in range(32, 127):
    i = c - 32
    d.text(((i % COLS) * CW, (i // COLS) * CH - 1), chr(c), fill=255, font=font)
w, h = img.size
data = img.tobytes()
with open('src/render/hudfont.h', 'w') as f:
    f.write('// generated by tools/gen_font.py (DejaVu Sans Mono Bold, Bitstream Vera licence)\n#pragma once\n')
    f.write(f'static const int kFontCellW = {CW}, kFontCellH = {CH}, kFontCols = {COLS}, kFontW = {w}, kFontH = {h};\n')
    f.write('static const unsigned char kFontAlpha[] = {' + ','.join(str(b) for b in data) + '};\n')

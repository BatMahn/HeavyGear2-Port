#!/bin/sh
# Regenerates shaders/gen/*.h: SPIR-V (Vulkan), MSL (Metal) and, when dxc is available, DXIL (Direct3D 12).
# Needs glslangValidator + spirv-cross; DXIL also needs dxc (set DXC=/path/to/dxc, e.g. from the
# DirectXShaderCompiler release archive, which signs the output when libdxil sits next to it).
set -e
cd "$(dirname "$0")"
mkdir -p gen
DXC=${DXC:-$(command -v dxc || true)}
for s in world.vert world.frag; do
  n=$(echo $s | tr . _)
  glslangValidator -V --quiet -o gen/$n.spv $s
  spirv-cross gen/$n.spv --msl --msl-version 20000 --output gen/$n.metal
  # HLSL keeps SDL_GPU's register spaces (vertex uniforms b0/space1, fragment t0,s0/space2 and b0/space3)
  spirv-cross gen/$n.spv --hlsl --shader-model 60 --output gen/$n.hlsl
  if [ -n "$DXC" ]; then
    prof=vs_6_0; [ "$s" = world.frag ] && prof=ps_6_0
    "$DXC" -T $prof -E main -Fo gen/$n.dxil gen/$n.hlsl >/dev/null
  fi
  python3 - "$n" <<'PY'
import sys, os
n=sys.argv[1]
spv=open(f'gen/{n}.spv','rb').read()
msl=open(f'gen/{n}.metal').read()
dxil=open(f'gen/{n}.dxil','rb').read() if os.path.exists(f'gen/{n}.dxil') else b''
with open(f'gen/{n}.h','w') as f:
    f.write(f'// generated by shaders/gen.sh from {n.replace("_",".")}\n#pragma once\n')
    f.write(f'static const unsigned char {n}_spv[] = {{' + ','.join(str(b) for b in spv) + '};\n')
    f.write(f'static const char {n}_msl[] = ' + ''.join('"'+l.replace('\\','\\\\').replace('"','\\"')+'\\n"\n' for l in msl.split('\n')) + ';\n')
    if dxil:
        f.write(f'#define {n.upper()}_HAS_DXIL 1\n')
        f.write(f'static const unsigned char {n}_dxil[] = {{' + ','.join(str(b) for b in dxil) + '};\n')
PY
  rm -f gen/$n.spv gen/$n.metal gen/$n.dxil gen/$n.hlsl
done
